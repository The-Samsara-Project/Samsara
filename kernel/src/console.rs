//! Text console rendered on the linear framebuffer.
//!
//! When the bootloader hands over a supported graphics mode the kernel draws
//! an 8x8 bitmap font straight into the framebuffer, with a block cursor,
//! per-byte colors and scrolling. The console parses a practical subset of
//! ANSI SGR escapes (`\x1b[...m`, plain and truecolor) so each log segment —
//! timestamp, level tag, message — can carry its own color instead of one
//! attribute per whole line. Without a framebuffer the console stays silent
//! (only a `None` exists) and logging goes out over the debug UART.

use crate::framebuffer;
use crate::sync::Spinlock;

/// Width of one source glyph in pixels.
const GLYPH_W: usize = 8;
/// Height of one source glyph in pixels.
const GLYPH_H: usize = 8;
/// Horizontal source-pixel scale.  Keeping this at one preserves 128 columns
/// on a 1024-pixel framebuffer, as on a classic Linux VGA console.
const FONT_SCALE_X: usize = 1;
/// Vertical source-pixel scale.
const FONT_SCALE_Y: usize = 1;
/// Empty pixels left between text rows for legible log separation.  The gap
/// is split above and below each glyph so consecutive lines (for example
/// timestamped log entries) read as clearly separated rows instead of one
/// crammed block.
const LINE_GAP: usize = 4;
/// Blank pixel rows above each glyph; the rest of [`LINE_GAP`] falls below it.
const GLYPH_OFFSET_Y: usize = LINE_GAP / 2;
/// Width of one rendered text cell in pixels.
pub const FONT_W: usize = GLYPH_W * FONT_SCALE_X;
/// Height of one rendered text cell in pixels.
pub const FONT_H: usize = GLYPH_H * FONT_SCALE_Y + LINE_GAP;

/// Default light-grey foreground index (palette entry 7).
const PEN_DEFAULT: u8 = 0x07;

