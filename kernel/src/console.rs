/// State of a minimal ANSI escape-sequence parser.
struct Ansi {
    /// 0 = plain text, 1 = `ESC` seen, 2 = CSI (collecting parameters).
    state: u8,
    /// Parameter bytes captured so far (digits and `;`).
    buf: [u8; 32],
    len: usize,
}

impl Ansi {
    const fn new() -> Self {
        Self { state: 0, buf: [0; 32], len: 0 }
    }
}

/// A text cell renderer tied to one row/column grid over the framebuffer.
///
/// The pen tracks a packed foreground/background color plus the ANSI bold
/// flag; each glyph is drawn with the colors in effect at the moment its
/// byte streams through, so one line can be divided into differently colored
/// segments.
struct Console {
    cols: usize,
    rows: usize,
    col: usize,
    row: usize,
    /// Packed foreground color of the current pen.
    fg: u32,
    /// Packed background color of the current pen.
    bg: u32,
    /// ANSI bold attribute; brightens indexed (non-truecolor) colors.
    bold: bool,
    ansi: Ansi,
}

impl Console {
    fn fb() -> Option<&'static framebuffer::Framebuffer> {
        framebuffer::get()
    }

    /// Resolve an ANSI color number (0..=15, bit 3 set for the bright
    /// variants) to a packed pixel color. `allow_bold` lets the pen's bold
    /// attribute brighten the color; terminals only brighten the foreground,
    /// so background callers pass `false`.
    fn indexed(&self, fb: &framebuffer::Framebuffer, ansi: u8, allow_bold: bool) -> u32 {
        let idx = ANSI_TO_VGA[(ansi & 0x07) as usize];
        let bright = ansi & 0x08 != 0 || (allow_bold && self.bold);
        fb.packed(if bright { idx | 0x08 } else { idx })
    }

    /// Apply an SGR (`\x1b[...m`) parameter list to the pen.
    fn apply_sgr(&mut self) {
        let Some(fb) = Self::fb() else { return };

        // Split the captured parameter bytes into values; absent entries
        // (e.g. `\x1b[1;;31m`) read as zero, and an empty `\x1b[m` resets.
        let mut params: [i32; 32] = [0; 32];
        let mut n = 0;
        let mut acc = 0i32;
        let mut seen = false;
        for &b in self.ansi.buf[..self.ansi.len].iter().chain(&[b';']) {
            if b.is_ascii_digit() {
                acc = acc.saturating_mul(10).saturating_add((b - b'0') as i32);
                seen = true;
            } else {
                if n < params.len() {
                    params[n] = if seen { acc } else { 0 };
                    n += 1;
                }
                acc = 0;
                seen = false;
            }
        }

        let mut i = 0;
        while i < n {
            let p = params[i];
            let mut adv = 1;
            match p {
                0 => {
                    self.fg = fb.packed(PEN_DEFAULT);
                    self.bg = 0;
                    self.bold = false;
                }
                1 => self.bold = true,
                2 | 21 => {}
                22 => self.bold = false,
                30..=37 => self.fg = self.indexed(fb, (p - 30) as u8, true),
                39 => self.fg = fb.packed(PEN_DEFAULT),
                40..=47 => self.bg = self.indexed(fb, (p - 40) as u8, false),
                49 => self.bg = 0,
                90..=97 => self.fg = self.indexed(fb, ((p - 90) as u8) | 8, true),
                100..=107 => self.bg = self.indexed(fb, ((p - 100) as u8) | 8, false),
                38 | 48 => {
                    let is_fg = p == 38;
                    if i + 1 < n {
                        match params[i + 1] {
                            5 if i + 2 < n => {
                                let (r, g, b) = xterm_rgb(params[i + 2] as usize);
                                let c = fb.packed(fb.closest_palette(r, g, b));
                                if is_fg {
                                    self.fg = c;
                                } else {
                                    self.bg = c;
                                }
                                adv = 3;
                            }
                            2 if i + 4 < n => {
                                let c = fb.pack_rgb(
                                    params[i + 2] as u8,
                                    params[i + 3] as u8,
                                    params[i + 4] as u8,
                                );
                                if is_fg {
                                    self.fg = c;
                                } else {
                                    self.bg = c;
                                }
                                adv = 5;
                            }
                            _ => adv = 2,
                        }
                    }
                }
                _ => {}
            }
            i += adv;
        }
    }

    /// Fill one cell with the background color, erasing any cursor block.
    fn blank_cell(&mut self, col: usize, row: usize) {
        if let Some(fb) = Self::fb() {
            fb.fill_rect(col * FONT_W, row * FONT_H, FONT_W, FONT_H, self.bg);
        }
    }

    /// Draw `ch` into a cell using the pen colors, centered as usual.
    fn draw_cell(&mut self, col: usize, row: usize, ch: u8) {
        let Some(fb) = Self::fb() else { return };
        let fg = self.fg;
        let bg = self.bg;
        let x0 = col * FONT_W;
        let y0 = row * FONT_H;
        fb.fill_rect(x0, y0, FONT_W, FONT_H, bg);
        let glyph = FONT[(if ch < 0x80 { ch } else { b'?' }) as usize];
        for (ry, &row_bits) in glyph.iter().enumerate() {
            for cx in 0..GLYPH_W {
                // The CP437 rows are little-endian bitmaps: bit 0 is the left
                // edge, drawn here with `1 << cx`.
                if row_bits & (1 << cx) != 0 {
                    fb.fill_rect(
                        x0 + cx * FONT_SCALE_X,
                        y0 + GLYPH_OFFSET_Y + ry * FONT_SCALE_Y,
                        FONT_SCALE_X,
                        FONT_SCALE_Y,
                        fg,
                    );
                }
            }
        }
    }

    /// Paint the block cursor. A cursor parked past the last column wraps to
    /// the start of the next line, mirroring how the old hardware cursor
    /// behaved on a full row.
    fn cursor_cell(&mut self) {
        let mut col = self.col;
        let mut row = self.row;
        if col >= self.cols {
            col = 0;
            row += 1;
            if row >= self.rows {
                row = self.rows - 1;
            }
        }
        if let Some(fb) = Self::fb() {
            fb.fill_rect(col * FONT_W, row * FONT_H, FONT_W, FONT_H, self.fg);
        }
    }

    fn advance_row(&mut self) {
        self.row += 1;
        if self.row >= self.rows {
            if let Some(fb) = Self::fb() {
                fb.scroll_up(FONT_H);
            }
            self.row = self.rows - 1;
            let fb = Self::fb().unwrap();
            fb.fill_rect(
                0,
                self.row * FONT_H,
                self.cols * FONT_W,
                FONT_H,
                self.bg,
            );
            self.col = 0;
        }
    }

    fn write_byte(&mut self, byte: u8) {
        match self.ansi.state {
            // After ESC: expect the `[` of a CSI sequence.
            1 => {
                if byte == b'[' {
                    self.ansi.state = 2;
                    self.ansi.len = 0;
                } else {
                    self.ansi.state = 0;
                }
                return;
            }
            // CSI: collect parameter bytes, then act on the final byte.
            2 => {
                if (0x30..=0x3F).contains(&byte) {
                    if self.ansi.len < self.ansi.buf.len() {
                        self.ansi.buf[self.ansi.len] = byte;
                        self.ansi.len += 1;
                    }
                    return;
                }
                if (0x40..=0x7E).contains(&byte) {
                    if byte == b'm' {
                        self.apply_sgr();
                    }
                }
                self.ansi.state = 0;
                return;
            }
            _ => {}
        }

        match byte {
            b'\n' => {
                self.blank_cell(self.col, self.row);
                self.col = 0;
                self.advance_row();
            }
            b'\r' => {
                self.blank_cell(self.col, self.row);
                self.col = 0;
            }
            0x08 => {
                self.blank_cell(self.col, self.row);
                if self.col > 0 {
                    self.col -= 1;
                    self.blank_cell(self.col, self.row);
                }
            }
            0x1B => {
                self.ansi.state = 1;
            }
            b if b <= 0x1F || b == 0x7F => {}
            b => {
                if self.col >= self.cols {
                    self.col = 0;
                    self.advance_row();
                }
                self.draw_cell(self.col, self.row, b);
                self.col += 1;
            }
        }
    }

    fn write(&mut self, bytes: &[u8]) {
        for &b in bytes {
            self.write_byte(b);
        }
    }

    fn clear(&mut self) {
        if let Some(fb) = Self::fb() {
            fb.fill(self.bg);
        }
        self.col = 0;
        self.row = 0;
    }
}

/// RGB value of an xterm 256-color palette entry (index 0..=255).
fn xterm_rgb(idx: usize) -> (u8, u8, u8) {
    const BASIC: [(u8, u8, u8); 16] = [
        (0x00, 0x00, 0x00),
        (0x80, 0x00, 0x00),
        (0x00, 0x80, 0x00),
        (0x80, 0x80, 0x00),
        (0x00, 0x00, 0x80),
        (0x80, 0x00, 0x80),
        (0x00, 0x80, 0x80),
        (0xC0, 0xC0, 0xC0),
        (0x80, 0x80, 0x80),
        (0xFF, 0x00, 0x00),
        (0x00, 0xFF, 0x00),
        (0xFF, 0xFF, 0x00),
        (0x00, 0x00, 0xFF),
        (0xFF, 0x00, 0xFF),
        (0x00, 0xFF, 0xFF),
        (0xFF, 0xFF, 0xFF),
    ];
    match idx {
        0..=15 => BASIC[idx],
        16..=231 => {
            let q = idx - 16;
            let cube = |c: usize| [0, 95, 135, 175, 215, 255][c];
            (cube(q / 36), cube((q / 6) % 6), cube(q % 6))
        }
        _ => {
            let v = 8 + (idx - 232) * 10;
            (v as u8, v as u8, v as u8)
        }
    }
}

static CONSOLE: Spinlock<Option<Console>> = Spinlock::new(None);

/// Bring up the console on the framebuffer (if one is active): clear the
/// screen, reset the cursor and show the initial cursor block.
pub fn init() {
    let mut guard = CONSOLE.lock();
    let Some(fb) = framebuffer::get() else {
        *guard = None;
        return;
    };
    let cols = fb.width() / FONT_W;
    let rows = fb.height() / FONT_H;
    if cols == 0 || rows == 0 {
        *guard = None;
        return;
    }
    let mut con = Console {
        cols,
        rows,
        col: 0,
        row: 0,
        fg: fb.packed(PEN_DEFAULT),
        bg: 0,
        bold: false,
        ansi: Ansi::new(),
    };
    con.clear();
    con.cursor_cell();
    *guard = Some(con);
}

/// Write raw bytes to the console (used by the logger and panics).
pub fn write(bytes: &[u8]) {
    let mut guard = CONSOLE.lock();
    if let Some(con) = guard.as_mut() {
        con.write(bytes);
        con.cursor_cell();
    }
}

/// Whether a framebuffer console is currently active.
pub fn active() -> bool {
    CONSOLE.lock().is_some()
}

/// The console's text-mode geometry, as `TIOCGWINSZ` reports it.
///
/// A program asks this to size its drawing, so an inactive console reports a
/// conventional 80x24 rather than zeroes -- a zero-sized terminal makes
/// line-wrapping arithmetic divide by zero in callers that trust the answer.
pub fn winsize() -> crate::drivers::pty::Winsize {
    let guard = CONSOLE.lock();
    match guard.as_ref() {
        Some(con) => crate::drivers::pty::Winsize {
            ws_row: con.rows as u16,
            ws_col: con.cols as u16,
            ws_xpixel: 0,
            ws_ypixel: 0,
        },
        None => crate::drivers::pty::Winsize {
            ws_row: 24,
            ws_col: 80,
            ws_xpixel: 0,
            ws_ypixel: 0,
        },
    }
}

/// Give up ownership of the framebuffer so a ring-3 terminal can draw to it
/// directly. Subsequent kernel/user log output is still emitted on the debug
/// UART but no longer paints over the display.
pub fn detach() {
    *CONSOLE.lock() = None;
}

/// Final safety net for the panic path: best-effort, lock-free.
///
/// A framebuffer console has no hardware cursor to park; the block cursor
/// just stays where the panic left it.
pub fn freeze_output() {}
